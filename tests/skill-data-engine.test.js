"use strict";
const assert = require("node:assert/strict");
const engine = require("../skill-data-engine.js");
const payload = {
  abilities: {
    earthshaker_echo_slam: {
      dname:"Echo Slam",desc:"Deals damage and stuns enemies.",
      notes:["Echoes are generated by nearby units."],cd:[150,130,110],
      mc:[150,225,300],dmg:[100,150,200],dmg_type:"magical",behavior:"AOE",
      attrib:[{key:"radius",value:"600"}]
    },
    spirit_breaker_charge_of_darkness: {
      dname:"Charge of Darkness",desc:"Charges toward an enemy.",
      cd:[12,10,8],mc:[90,90,90],radius:275
    }
  },
  heroAbilities: {
    npc_dota_hero_earthshaker:{abilities:["earthshaker_echo_slam","earthshaker_aftershock"],talents:[{name:"special_bonus_attack_damage"}]},
    npc_dota_hero_spirit_breaker:{abilities:["spirit_breaker_charge_of_darkness","missing_ability"]}
  },
  heroes:[{id:7,localized_name:"Earthshaker"},{id:71,localized_name:"Spirit Breaker"}]
};
const dataset=engine.buildDataset(payload,{patch:"7.42",fetchedAt:"2026-11-18T00:00:00.000Z"});
assert.equal(dataset.counts.heroes,2);
assert.equal(dataset.counts.abilities,2);
assert.equal(engine.findAbility(dataset,"earthshaker_echo_slam").displayName,"Echo Slam");
assert.deepEqual(engine.findAbility(dataset,"earthshaker_echo_slam").cooldown,[150,130,110]);
assert.equal(engine.findAbility(dataset,"spirit_breaker_charge_of_darkness").radius,275);
assert.equal(engine.getHeroSkills(dataset,"npc_dota_hero_spirit_breaker").abilities[1].missingMetadata,true);
assert.equal(engine.getCoverage(dataset).abilitySlots,4);
assert.equal(engine.getCoverage(dataset).missingMetadataSlots,2);
(async()=>{
  const calls=[];
  const mockFetch=async url=>{
    calls.push(url); const key=url.split("/").pop();
    const data=key==="abilities"?payload.abilities:key==="hero_abilities"?payload.heroAbilities:payload.heroes;
    return {ok:true,json:async()=>data};
  };
  const loaded=await engine.load({fetch:mockFetch,baseUrl:"https://example.test/api",force:true});
  assert.equal(loaded.counts.heroes,2);
  assert.equal(calls.length,3);
  assert.ok(calls.some(url=>url.endsWith("/constants/abilities")));
  assert.ok(calls.some(url=>url.endsWith("/constants/hero_abilities")));
  assert.ok(calls.some(url=>url.endsWith("/constants/heroes")));
  console.log("Skill data engine: extraction, normalization, coverage and source adapter passed.");
})().catch(error=>{console.error(error);process.exitCode=1;});

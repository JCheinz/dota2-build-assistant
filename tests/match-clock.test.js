const assert=require("node:assert/strict");
const {create,phases}=require("../match-clock.js");
class MemoryStorage{constructor(){this.data=new Map()}getItem(k){return this.data.get(k)||null}setItem(k,v){this.data.set(k,v)}}
const storage=new MemoryStorage();
let now=1000;
const clock=create({storage,now:()=>now});
assert.deepEqual(clock.snapshot(),{elapsedMs:0,elapsedSeconds:0,minute:0,second:0,running:false,phase:phases[0]});
assert.equal(clock.start(),true);
now=61000;
assert.equal(clock.snapshot().elapsedSeconds,60);
assert.equal(clock.snapshot().minute,1);
assert.equal(clock.pause(),true);
const paused=clock.snapshot();
now=91000;
assert.equal(clock.snapshot().elapsedMs,paused.elapsedMs,"El reloj pausado no debe avanzar.");
assert.equal(clock.snapshot().running,false);
assert.equal(clock.start(),true);
now=151000;
assert.equal(clock.snapshot().elapsedSeconds,120);
const restored=create({storage,now:()=>now});
assert.equal(restored.snapshot().elapsedSeconds,120,"El reloj en curso debe recuperarse sin perder el tiempo transcurrido.");
assert.equal(restored.pause(),true);
const frozen=restored.snapshot().elapsedMs;
now+=120000;
assert.equal(restored.snapshot().elapsedMs,frozen,"La pausa recuperada debe seguir congelada.");
assert.equal(restored.phaseAt(11).key,"early");
assert.equal(restored.phaseAt(12).key,"mid");
assert.equal(restored.phaseAt(24).key,"mid");
assert.equal(restored.phaseAt(25).key,"late");
restored.reset();
assert.equal(restored.snapshot().elapsedSeconds,0);
assert.equal(restored.snapshot().running,false);
console.log("OK: reloj persistente — iniciar, pausar, reanudar, recuperar, fases 12/25 y reiniciar");
